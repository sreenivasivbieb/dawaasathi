"""Write web/i18n/terms.js (usual-use words, dosage forms, release types, pack units) from the
reply templates in app/dialogue/templates/*.json, so the screen and the spoken reply use the same
words. Run after editing a template:  uv run python -m scripts.gen_web_i18n"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "app" / "dialogue" / "templates"
OUT = ROOT / "web" / "i18n" / "terms.js"
SKIP = {"hi", "en", "mr"}  # written by hand in web/i18n.js


def main() -> None:
    terms: dict[str, dict] = {}
    for path in sorted(SRC.glob("*.json")):
        lang = path.stem
        if lang in SKIP:
            continue
        t = json.loads(path.read_text(encoding="utf-8"))
        w = t["words"]
        terms[lang] = {
            "USES": t["uses"], "FORMS": t.get("forms", {}), "RELEASES": t.get("releases", {}),
            "PACK_UNITS": {"tablets": w["unit_tablet"], "capsules": w["unit_capsule"], "ml": w["unit_ml"]},
        }
    body = json.dumps(terms, ensure_ascii=False, indent=1)
    OUT.write_text("// Generated by scripts/gen_web_i18n.py from app/dialogue/templates/*.json. Do not edit.\n"
                   f"export const TERMS = {body};\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({', '.join(terms)})")


if __name__ == "__main__":
    main()
