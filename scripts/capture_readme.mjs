// Capture actual UI screens against an isolated demo server. Run from the repository root.
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import {writeFile} from 'node:fs/promises';
const b=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const context=await b.newContext({viewport:{width:1440,height:1100},deviceScaleFactor:1,reducedMotion:'reduce'});
const base=process.env.DAWA_DOCS_URL || 'http://127.0.0.1:8004';
const page=await context.newPage();const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(base,{waitUntil:'networkidle'});
await page.locator('#voice-badge').waitFor();
await page.screenshot({path:'docs/screenshots/desktop.png',fullPage:true});
await page.locator('#auto-speak').uncheck();
await page.locator('#q').fill('Dolo 650 price and generic');await page.locator('#send').click();
await page.locator('#result .card').waitFor();await page.waitForFunction(()=>document.querySelector('.results').getAttribute('aria-busy')==='false');
await page.screenshot({path:'docs/screenshots/medicine-result.png',fullPage:true});
await page.locator('#btn-new').click();
await page.locator('#in-strip').setInputFiles('samples/strip_glycomet_sr_500.png');
await page.locator('#in-rx').setInputFiles('samples/rx_glycomet_500.png');
await page.locator('#send').click();await page.locator('#result .cmp').waitFor({timeout:60000});
await page.locator('#result').screenshot({path:'docs/screenshots/prescription-comparison.png'});
await page.locator('#lang').selectOption('hi');await page.waitForFunction(()=>document.documentElement.lang==='hi'&&document.querySelector('.results').getAttribute('aria-busy')==='false');
await page.locator('#btn-new').click();
await page.screenshot({path:'docs/screenshots/hindi.png',fullPage:true});
await page.locator('#lang').selectOption('en');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'docs/screenshots/mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const report={captured_at:new Date().toISOString(),base_url:base,browser:'Chromium (headless)',desktop:{width:1440,height:1100},mobile:{width:390,height:844},screenshots:5,pageErrors:errors,mobileHorizontalOverflow:overflow,configuration:await (await page.request.get(base+'/v1/config')).json(),synthetic_samples:true,live_voice_tested:false};
await writeFile('docs/screenshots/capture.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({screenshots:5,pageErrors:errors,mobileHorizontalOverflow:overflow}));
const threads=await page.evaluate(()=>JSON.parse(localStorage.getItem('momo.threads')||'[]'));
for(const id of threads)await page.request.delete(base+'/v1/threads/'+id);
await b.close();
