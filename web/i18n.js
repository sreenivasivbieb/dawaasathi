function fill(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
}

const pick = (table, lang, key) => (table[lang] && table[lang][key]) ?? (table.en && table.en[key]);

/** UI string in `lang` (falls back to English, then to the key itself). */
export function t(lang, key, vars) {
  return fill(pick(S, lang, key) ?? key, vars);
}
/** English sub-label for a key, or "" when the UI is already English. */
export function sub(lang, key, vars) {
  return "";
}
export function verdictTitle(lang, key) {
  return pick(VERDICT, lang, key) ?? key;
}
export function flagLabel(lang, code) {
  return pick(FLAGS, lang, code) ?? code.replace(/_/g, " ").toLowerCase();
}
export function useWord(lang, tag) {
  return pick(USES, lang, tag) ?? tag;
}
export function formLabel(lang, form) {
  return form ? (FORMS[form]?.[lang] ?? form.replace(/_/g, " ")) : "";
}
export function releaseLabel(lang, rel) {
  return rel ? (RELEASES[rel]?.[lang] ?? rel) : "";
}
export function packUnit(lang, unit, form) {
  const u = unit || (form === "capsule" ? "capsules" : form === "tablet" ? "tablets" : "");
  return PACK_UNITS[u]?.[lang] ?? u;
}
export function symptomChips(lang) {
  // Other languages send the English phrase: the backend's symptom words always cover it.
  const send = SYMPTOM_SEND[lang] || SYMPTOM_SEND.en;
  return SYMPTOM_KEYS.map((k) => ({ key: k, label: useWord(lang, k), en: lang === "en" ? "" : USES.en[k], send: send(k) }));
}
